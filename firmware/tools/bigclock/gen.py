from font import *
out=["// Generated by /workspace/bigclock/gen.py — big-clock digit bitmaps.",
"// 10 digits, %dx%d px, one uint32_t per row (bit %d = leftmost column)."%(W,H,W-1),
"#pragma once","#include <Arduino.h>",
f"#define BIGCLK_W {W}",f"#define BIGCLK_H {H}",
"static const uint32_t BIGCLK_FONT[10][BIGCLK_H] PROGMEM = {"]
for c in '0123456789':
    rows=[sum(1<<(W-1-x) for x in range(W) if FONT[c][y][x]) for y in range(H)]
    out.append("  {"+",".join("0x%05X"%r for r in rows)+"},")
out.append("};")
out.append("// Color presets (index = clockColor). Date uses ~%d%% of the same color."%int(DIM*100))
out.append("static const uint8_t BIGCLK_COLORS[%d][3] = {"%len(COLORS))
for n,(r,g,b) in COLORS: out.append(f"  {{{r},{g},{b}}},  // {n}")
out.append("};")
out.append(f"#define BIGCLK_NCOLORS {len(COLORS)}")
open("/workspace/Info-Wall/firmware/include/BigClockFont.h","w").write("\n".join(out)+"\n")
